use cartograph_core::diagram::{
    DiagramDiffStatus, DiagramEdgeStyle, DiagramGraph, DiagramTheme,
};
use cartograph_core::model::NodeKind;

pub struct SvgRenderer;

impl SvgRenderer {
    pub fn render(graph: &DiagramGraph, theme: DiagramTheme) -> String {
        let is_dark = matches!(theme, DiagramTheme::Dark | DiagramTheme::HighContrast);

        // Calculate total canvas bounds
        let mut min_x = 0.0f64;
        let mut min_y = 0.0f64;
        let mut max_x = 600.0f64;
        let mut max_y = 400.0f64;

        for node in &graph.nodes {
            min_x = min_x.min(node.layout.x - 20.0);
            min_y = min_y.min(node.layout.y - 20.0);
            max_x = max_x.max(node.layout.x + node.layout.width + 40.0);
            max_y = max_y.max(node.layout.y + node.layout.height + 40.0);
        }

        for cluster in &graph.clusters {
            min_x = min_x.min(cluster.bounds.x - 10.0);
            min_y = min_y.min(cluster.bounds.y - 10.0);
            max_x = max_x.max(cluster.bounds.x + cluster.bounds.width + 10.0);
            max_y = max_y.max(cluster.bounds.y + cluster.bounds.height + 10.0);
        }

        let width = (max_x - min_x).max(800.0);
        let height = (max_y - min_y).max(600.0);

        let bg_color = if is_dark { "#0f172a" } else { "#f8fafc" };
        let node_bg = if is_dark { "#1e293b" } else { "#ffffff" };
        let node_border = if is_dark { "#334155" } else { "#cbd5e1" };
        let text_color = if is_dark { "#f8fafc" } else { "#0f172a" };
        let subtext_color = if is_dark { "#94a3b8" } else { "#64748b" };
        let edge_color = if is_dark { "#64748b" } else { "#94a3b8" };
        let cluster_bg = if is_dark { "#1e293b1a" } else { "#f1f5f980" };
        let cluster_border = if is_dark { "#475569" } else { "#94a3b8" };
        let accent_color = "#6366f1";

        let mut svg = String::new();
        svg.push_str(&format!(
            r#"<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="{min_x} {min_y} {width} {height}" width="100%" height="100%" style="background-color: {bg_color}; font-family: Inter, system-ui, -apple-system, sans-serif;">
"#
        ));

        // SVG Definitions (Gradients, Markers, Filters)
        svg.push_str(&format!(
            r##"  <defs>
    <filter id="node-shadow" x="-10%" y="-10%" width="120%" height="120%">
      <feDropShadow dx="0" dy="4" stdDeviation="6" flood-color="#000000" flood-opacity="0.15" />
    </filter>
    <marker id="marker-arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="6" markerHeight="6" orient="auto-start-reverse">
      <path d="M 0 1 L 10 5 L 0 9 z" fill="{edge_color}" />
    </marker>
    <marker id="marker-warning" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="6" markerHeight="6" orient="auto-start-reverse">
      <path d="M 0 1 L 10 5 L 0 9 z" fill="#ef4444" />
    </marker>
    <marker id="marker-accent" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="6" markerHeight="6" orient="auto-start-reverse">
      <path d="M 0 1 L 10 5 L 0 9 z" fill="{accent_color}" />
    </marker>
    <style>
      .node-link {{ text-decoration: none; }}
      .node-box {{ transition: all 0.2s ease; cursor: pointer; }}
      .node-box:hover {{ stroke: {accent_color}; stroke-width: 2.5px; filter: drop-shadow(0 0 10px rgba(99, 102, 241, 0.4)); }}
      .edge-path {{ transition: stroke 0.2s ease; }}
      .edge-path:hover {{ stroke: {accent_color}; stroke-width: 2.5px; }}
    </style>
  </defs>
"##
        ));

        // Header Title Banner
        svg.push_str(&format!(
            r#"  <g id="header" transform="translate(40, 40)">
    <text x="0" y="0" font-size="20" font-weight="700" fill="{text_color}">{title}</text>
    <text x="0" y="22" font-size="12" fill="{subtext_color}">Generated by Cartograph • {nodes_count} nodes • {edges_count} connections</text>
  </g>
"#,
            title = escape_xml(&graph.title),
            nodes_count = graph.nodes.len(),
            edges_count = graph.edges.len(),
        ));

        // Render Clusters
        svg.push_str("  <g id=\"clusters\">\n");
        for cluster in &graph.clusters {
            if cluster.bounds.width > 0.0 && cluster.bounds.height > 0.0 {
                svg.push_str(&format!(
                    r#"    <g class="cluster" id="{id}">
      <rect x="{x}" y="{y}" width="{w}" height="{h}" rx="10" ry="10" fill="{cluster_bg}" stroke="{cluster_border}" stroke-width="1.5" stroke-dasharray="4 4" />
      <text x="{tx}" y="{ty}" font-size="12" font-weight="600" fill="{subtext_color}" text-transform="uppercase" letter-spacing="1">📦 {label}</text>
    </g>
"#,
                    id = cluster.id,
                    x = cluster.bounds.x,
                    y = cluster.bounds.y,
                    w = cluster.bounds.width,
                    h = cluster.bounds.height,
                    tx = cluster.bounds.x + 15.0,
                    ty = cluster.bounds.y + 16.0,
                    label = escape_xml(&cluster.label),
                ));
            }
        }
        svg.push_str("  </g>\n");

        // Render Edges
        svg.push_str("  <g id=\"edges\">\n");
        for edge in &graph.edges {
            if edge.waypoints.len() >= 4 {
                let p0 = edge.waypoints[0];
                let p1 = edge.waypoints[1];
                let p2 = edge.waypoints[2];
                let p3 = edge.waypoints[3];

                let (stroke_color, marker_id, dash_attr, stroke_w) = match edge.style {
                    DiagramEdgeStyle::BoldWarning => ("#ef4444", "marker-warning", "", 2.5),
                    DiagramEdgeStyle::Dashed => (edge_color, "marker-arrow", "stroke-dasharray=\"5 4\"", 1.5),
                    DiagramEdgeStyle::Dotted => (edge_color, "marker-arrow", "stroke-dasharray=\"2 3\"", 1.5),
                    DiagramEdgeStyle::Solid => (edge_color, "marker-arrow", "", 1.5),
                };

                svg.push_str(&format!(
                    r#"    <path class="edge-path" d="M {x0} {y0} C {x1} {y1}, {x2} {y2}, {x3} {y3}" fill="none" stroke="{stroke_color}" stroke-width="{stroke_w}" {dash_attr} marker-end="url(#{marker_id})" />
"#,
                    x0 = p0.x,
                    y0 = p0.y,
                    x1 = p1.x,
                    y1 = p1.y,
                    x2 = p2.x,
                    y2 = p2.y,
                    x3 = p3.x,
                    y3 = p3.y,
                ));

                // Optional Edge Label
                if let Some(lbl) = &edge.label {
                    let mid_x = (p0.x + p3.x) / 2.0;
                    let mid_y = (p0.y + p3.y) / 2.0 - 6.0;
                    svg.push_str(&format!(
                        r#"    <text x="{mid_x}" y="{mid_y}" font-size="10" font-weight="500" fill="{subtext_color}" text-anchor="middle" background="{bg_color}">{lbl}</text>
"#,
                        lbl = escape_xml(lbl)
                    ));
                }
            }
        }
        svg.push_str("  </g>\n");

        // Render Nodes
        svg.push_str("  <g id=\"nodes\">\n");
        for node in &graph.nodes {
            let (border_color, stroke_width) = match node.diff_status {
                Some(DiagramDiffStatus::Modified) => ("#d97706", 2.5),
                Some(DiagramDiffStatus::Added) => ("#16a34a", 2.5),
                Some(DiagramDiffStatus::Deleted) => ("#dc2626", 2.5),
                Some(DiagramDiffStatus::BlastRadiusHazard) => ("#ea580c", 2.5),
                None => (node_border, 1.5),
            };

            let kind_icon = match node.kind {
                NodeKind::Function => "⚡",
                NodeKind::Method => "⚡",
                NodeKind::Struct => "📦",
                NodeKind::Class => "🏛️",
                NodeKind::Model => "🗄️",
                NodeKind::Interface => "🔌",
                NodeKind::Route => "🌐",
                NodeKind::Module => "📁",
                NodeKind::File => "📄",
                _ => "🔹",
            };

            let href = if !node.filepath.is_empty() {
                format!("file://{}#L{}", node.filepath, node.line_span.0)
            } else {
                "#".to_string()
            };

            svg.push_str(&format!(
                r#"    <a xlink:href="{href}" target="_blank" class="node-link">
      <g class="node-group" transform="translate({x}, {y})">
        <title>{label} ({kind})\nFile: {file}:{line}\n{subtitle}</title>
        <rect class="node-box" width="{w}" height="{h}" rx="8" ry="8" fill="{node_bg}" stroke="{border_color}" stroke-width="{stroke_width}" filter="url(#node-shadow)" />
        <text x="14" y="24" font-size="13" font-weight="600" fill="{text_color}">{icon} {label}</text>
"#,
                href = href,
                x = node.layout.x,
                y = node.layout.y,
                w = node.layout.width,
                h = node.layout.height,
                label = escape_xml(&node.label),
                kind = node.kind.as_str(),
                file = node.filepath,
                line = node.line_span.0,
                subtitle = escape_xml(node.subtitle.as_deref().unwrap_or("")),
                icon = kind_icon,
            ));

            // Subtitle / signature or coupling stats
            if let Some(sub) = &node.subtitle {
                svg.push_str(&format!(
                    r#"        <text x="14" y="44" font-size="10" font-family="ui-monospace, monospace" fill="{subtext_color}">{sub}</text>
"#,
                    sub = escape_xml(sub)
                ));
            }

            // ER Attributes list
            if !node.attributes.is_empty() {
                let mut attr_y = 48.0;
                for attr in &node.attributes {
                    let badge = if attr.is_pk {
                        "🔑 PK"
                    } else if attr.is_fk {
                        "🔗 FK"
                    } else {
                        "  "
                    };

                    svg.push_str(&format!(
                        r#"        <text x="14" y="{attr_y}" font-size="10" font-family="ui-monospace, monospace" fill="{text_color}">{badge} {name}: <tspan fill="{subtext_color}">{dtype}</tspan></text>
"#,
                        name = escape_xml(&attr.name),
                        dtype = escape_xml(&attr.data_type),
                    ));
                    attr_y += 20.0;
                }
            }

            svg.push_str("      </g>\n    </a>\n");
        }
        svg.push_str("  </g>\n");

        svg.push_str("</svg>\n");
        svg
    }
}

fn escape_xml(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&apos;")
}
