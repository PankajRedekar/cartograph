use cartograph_core::model::TestSelectionReport;

pub struct ScriptFormatter;

impl ScriptFormatter {
    pub fn format(report: &TestSelectionReport) -> String {
        let mut out = String::new();
        out.push_str("#!/usr/bin/env bash\n");
        out.push_str("set -euo pipefail\n\n");
        out.push_str("# Generated by cartograph test-selector\n");

        if report.is_zero_risk_bypass {
            out.push_str("echo \"⚡ Zero tests needed: docstring/comment/docs changes only. Exiting with success.\"\n");
            out.push_str("exit 0\n");
            return out;
        }

        if report.runner_invocations.is_empty() {
            out.push_str("echo \"No tests selected to execute.\"\n");
            out.push_str("exit 0\n");
            return out;
        }

        out.push_str(&format!(
            "echo \"🚀 Running {} selected test runner invocation(s)...\"\n\n",
            report.runner_invocations.len()
        ));

        for (idx, inv) in report.runner_invocations.iter().enumerate() {
            out.push_str(&format!("echo \"▶ [{}/{}] {}\"\n", idx + 1, report.runner_invocations.len(), inv.display_command));
            out.push_str(&format!("{}\n\n", inv.display_command));
        }

        out.push_str("echo \"✔ All predictive tests passed successfully!\"\n");
        out
    }
}
