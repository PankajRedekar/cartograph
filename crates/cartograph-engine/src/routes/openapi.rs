use cartograph_core::model::{FullStackRouteTrace, HttpMethod, RouteAuthKind};
use serde_json::json;

pub struct OpenApiSynthesizer;

impl OpenApiSynthesizer {
    /// Generate an OpenAPI 3.1.0 specification document from the full-stack route inventory
    pub fn synthesize(
        traces: &[FullStackRouteTrace],
        title: &str,
        version: &str,
    ) -> serde_json::Value {
        let mut paths_obj = serde_json::Map::new();
        let mut schemas_obj = serde_json::Map::new();

        for trace in traces {
            let path_key = &trace.normalized_path;
            let method_key = trace.method.as_str().to_lowercase();

            let path_entry = paths_obj
                .entry(path_key.clone())
                .or_insert_with(|| serde_json::Value::Object(serde_json::Map::new()));

            if let serde_json::Value::Object(map) = path_entry {
                let operation_id = trace
                    .handler
                    .as_ref()
                    .map(|h| h.name.clone())
                    .unwrap_or_else(|| {
                        format!(
                            "{}_{}",
                            method_key,
                            path_key
                                .trim_matches('/')
                                .replace('/', "_")
                                .replace(['{', '}'], "")
                        )
                    });

                // Path & query parameters
                let mut params_arr = Vec::new();
                for param in &trace.parameters {
                    params_arr.push(json!({
                        "name": param.name,
                        "in": "path",
                        "required": param.required,
                        "schema": {
                            "type": "string"
                        }
                    }));
                }

                let mut responses_obj = serde_json::Map::new();
                let status_code = if trace.method == HttpMethod::Post {
                    "201"
                } else {
                    "200"
                };

                // Response schema references models touched if available
                let response_content = if let Some(first_model) = trace.models_touched.first() {
                    let schema_ref = format!("#/components/schemas/{}", first_model.name);
                    schemas_obj.insert(
                        first_model.name.clone(),
                        json!({
                            "type": "object",
                            "title": first_model.name,
                            "description": format!("ORM Entity {}", first_model.name),
                        }),
                    );
                    json!({
                        "application/json": {
                            "schema": {
                                "$ref": schema_ref
                            }
                        }
                    })
                } else {
                    json!({
                        "application/json": {
                            "schema": {
                                "type": "object"
                            }
                        }
                    })
                };

                responses_obj.insert(
                    status_code.to_string(),
                    json!({
                        "description": "Successful operation",
                        "content": response_content
                    }),
                );

                let mut op_obj = json!({
                    "operationId": operation_id,
                    "summary": format!("{} {}", trace.method.as_str(), path_key),
                    "parameters": params_arr,
                    "responses": responses_obj,
                    "tags": [trace.framework.clone()]
                });

                if trace.auth == RouteAuthKind::Protected {
                    op_obj["security"] = json!([{ "BearerAuth": [] }]);
                }

                // If mutating, add placeholder request body
                if trace.is_mutation {
                    op_obj["requestBody"] = json!({
                        "required": true,
                        "content": {
                            "application/json": {
                                "schema": {
                                    "type": "object"
                                }
                            }
                        }
                    });
                }

                map.insert(method_key, op_obj);
            }
        }

        json!({
            "openapi": "3.1.0",
            "info": {
                "title": title,
                "version": version,
                "description": "Auto-synthesized full-stack API contract generated by Cartograph"
            },
            "paths": paths_obj,
            "components": {
                "schemas": schemas_obj,
                "securitySchemes": {
                    "BearerAuth": {
                        "type": "http",
                        "scheme": "bearer",
                        "bearerFormat": "JWT"
                    }
                }
            }
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_openapi_synthesis() {
        let traces = vec![FullStackRouteTrace {
            id: "1".into(),
            method: HttpMethod::Get,
            raw_pattern: "/api/users/:id".into(),
            normalized_path: "/api/users/{id}".into(),
            framework: "express".into(),
            filepath: "routes.ts".into(),
            line: 10,
            frontend_callers: vec![],
            parameters: vec![cartograph_core::model::RouteParameter {
                name: "id".into(),
                location: cartograph_core::model::ParamLocation::Path,
                type_hint: None,
                required: true,
                default_value: None,
                description: None,
            }],
            middlewares: vec![],
            handler: None,
            call_chain: vec![],
            models_touched: vec![],
            sql_tables: vec![],
            auth: RouteAuthKind::Protected,
            is_mutation: false,
            confidence: 1.0,
            issues: vec![],
        }];

        let doc = OpenApiSynthesizer::synthesize(&traces, "Test API", "1.0.0");
        assert_eq!(doc["openapi"], "3.1.0");
        assert_eq!(doc["info"]["title"], "Test API");
        assert!(doc["paths"]["/api/users/{id}"]["get"].is_object());
        assert_eq!(
            doc["paths"]["/api/users/{id}"]["get"]["security"][0]["BearerAuth"],
            json!([])
        );
    }
}
