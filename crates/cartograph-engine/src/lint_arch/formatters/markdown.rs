use cartograph_core::config::ArchSeverity;
use cartograph_core::model::{DependencyCycle, LintArchReport};

pub struct MarkdownFormatter;

impl MarkdownFormatter {
    pub fn format(report: &LintArchReport) -> String {
        let mut md = String::new();

        md.push_str("## 📐 Architectural Boundary & Dependency Report\n\n");

        // Status badge
        let status = if report.summary.passed {
            "✅ **Passed** (No Architectural Regressions)"
        } else {
            "❌ **Failed** (Architectural Violations Detected)"
        };
        md.push_str(&format!("**Status**: {status}  \n"));
        md.push_str(&format!("**Duration**: {:.2}ms  \n\n", report.summary.duration_micros as f64 / 1000.0));

        // Scorecard Table
        md.push_str("### Summary Scorecard\n\n");
        md.push_str("| Metric | Value |\n");
        md.push_str("| :--- | :--- |\n");
        md.push_str(&format!("| **Files Analyzed** | `{}` |\n", report.summary.files_analyzed));
        md.push_str(&format!("| **Dependency Edges Inspected** | `{}` |\n", report.summary.edges_inspected));
        md.push_str(&format!("| **Active Boundary Violations** | `{}` ({} errors, {} warnings) |\n",
            report.summary.active_violations_count,
            report.summary.active_errors_count,
            report.summary.active_warnings_count
        ));
        md.push_str(&format!("| **Baseline Suppressed Violations** | `{}` |\n", report.summary.baseline_suppressed_count));
        md.push_str(&format!("| **Circular Dependencies** | `{}` ({} runtime, {} type-only) |\n\n",
            report.summary.cycles_count,
            report.summary.runtime_cycles_count,
            report.summary.type_cycles_count
        ));

        // Cycles & Mermaid Diagrams
        if !report.cycles.is_empty() {
            md.push_str("### 🔄 Circular Dependencies\n\n");
            for (idx, cycle) in report.cycles.iter().enumerate() {
                md.push_str(&Self::format_cycle_markdown(idx + 1, cycle));
                md.push_str("\n\n");
            }
        }

        // Violations
        if !report.violations.is_empty() {
            md.push_str("### ⚠️ Boundary Violations\n\n");
            md.push_str("| Severity | Rule | Source | Target | Reason |\n");
            md.push_str("| :--- | :--- | :--- | :--- | :--- |\n");

            for v in &report.violations {
                let sev_icon = match v.severity {
                    ArchSeverity::Error => "🔴 Error",
                    ArchSeverity::Warning => "🟡 Warning",
                    ArchSeverity::Info => "ℹ️ Info",
                };

                let src = match v.line {
                    Some(l) => format!("`{}:{}`", v.source_file, l),
                    None => format!("`{}`", v.source_file),
                };

                md.push_str(&format!(
                    "| {} | `{}` | {} | `{}` | {} |\n",
                    sev_icon, v.rule_name, src, v.target_file, v.message
                ));
            }
            md.push_str("\n");

            // Collapsible details with remediation
            md.push_str("<details>\n<summary><b>🔍 Remediation Details & Advice</b></summary>\n\n");
            for v in &report.violations {
                md.push_str(&format!("#### Rule: `{}`\n", v.rule_name));
                md.push_str(&format!("- **Category**: `{}`\n", v.category));
                md.push_str(&format!("- **From**: `{}`\n", v.source_file));
                md.push_str(&format!("- **To**: `{}`\n", v.target_file));
                md.push_str(&format!("- **Issue**: {}\n", v.message));
                if let Some(ref hint) = v.remediation_hint {
                    md.push_str(&format!("- **Remediation**: {}\n", hint));
                }
                md.push_str("\n");
            }
            md.push_str("</details>\n\n");
        }

        md.push_str("---\n*Generated by `cartograph lint-arch`*\n");
        md
    }

    fn format_cycle_markdown(index: usize, cycle: &DependencyCycle) -> String {
        let mut s = String::new();
        let cycle_badge = if cycle.is_runtime_cycle {
            "🔴 **Runtime Cycle (Deadlock Risk)**"
        } else {
            "🟡 **Type-Only Cycle**"
        };

        s.push_str(&format!("#### Cycle #{index}: {cycle_badge}\n\n"));
        s.push_str(&format!("- **Length**: {} hops\n", cycle.length));

        if let Some(ref cut) = cycle.recommended_cut {
            s.push_str(&format!(
                "- **Suggested Cut**: Sever edge `{}` ➔ `{}` (resolves {} cycle{})\n",
                cut.source_file,
                cut.target_file,
                cut.cycles_broken_count,
                if cut.cycles_broken_count == 1 { "" } else { "s" }
            ));
            s.push_str(&format!("- **Refactoring Advice**: {}\n\n", cut.remediation_advice));
        }

        // Mermaid Graph LR
        s.push_str("```mermaid\ngraph LR\n");
        let n = cycle.hops.len();
        for (i, hop) in cycle.hops.iter().enumerate() {
            let next_idx = (i + 1) % n;
            let src_clean = Self::sanitize_id(&hop.name);
            let tgt_clean = Self::sanitize_id(&cycle.hops[next_idx].name);
            let label = if hop.is_runtime { "calls" } else { "types" };
            s.push_str(&format!("    {src_clean}[\"{}\"] -->|{label}| {tgt_clean}[\"{}\"]\n", hop.name, cycle.hops[next_idx].name));
        }
        s.push_str("```");

        s
    }

    fn sanitize_id(raw: &str) -> String {
        raw.chars()
            .map(|c| if c.is_alphanumeric() { c } else { '_' })
            .collect()
    }
}
