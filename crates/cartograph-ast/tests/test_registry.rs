use cartograph_ast::{AstRegistry, NodeKind, ParseOptions};

#[test]
fn test_registry_standard_polyglot_dispatch() {
    let registry = AstRegistry::standard();

    // Python
    let py_res = registry
        .parse_file("service.py", "def login(): pass", None)
        .expect("Python parse failed");
    assert_eq!(py_res.language, "python");
    assert_eq!(py_res.nodes.len(), 1);

    // TypeScript
    let ts_res = registry
        .parse_file("service.ts", "interface Config { port: number; }", None)
        .expect("TS parse failed");
    assert_eq!(ts_res.language, "typescript");
    assert_eq!(ts_res.nodes[0].kind, NodeKind::Interface);

    // React TSX
    let tsx_res = registry
        .parse_file(
            "Button.tsx",
            "export function Button() { return <button/>; }",
            None,
        )
        .expect("TSX parse failed");
    assert_eq!(tsx_res.language, "tsx");
    assert_eq!(tsx_res.nodes[0].kind, NodeKind::Component);

    // Ruby
    let rb_res = registry
        .parse_file("user.rb", "class User; def name; 'test'; end; end", None)
        .expect("Ruby parse failed");
    assert_eq!(rb_res.language, "ruby");

    // Rust
    let rs_res = registry
        .parse_file("lib.rs", "pub struct Client;", None)
        .expect("Rust parse failed");
    assert_eq!(rs_res.language, "rust");

    // Go
    let go_res = registry
        .parse_file("main.go", "package main\nfunc Run() {}", None)
        .expect("Go parse failed");
    assert_eq!(go_res.language, "go");

    // SQL
    let sql_res = registry
        .parse_file("schema.sql", "CREATE TABLE items (id INT);", None)
        .expect("SQL parse failed");
    assert_eq!(sql_res.language, "sql");

    // Markdown
    let md_res = registry
        .parse_file("README.md", "# Guide\nDetails here.", None)
        .expect("Markdown parse failed");
    assert_eq!(md_res.language, "markdown");
}

#[test]
fn test_registry_shebang_and_special_files() {
    let registry = AstRegistry::standard();

    // Extensionless Python script with shebang
    let py_script = "#!/usr/bin/env python3\ndef main(): pass";
    let res1 = registry
        .parse_file("bin/run_job", py_script, None)
        .expect("Shebang python failed");
    assert_eq!(res1.language, "python");

    // Special filename routes.rb
    let routes_code = "resources :projects";
    let res2 = registry
        .parse_file("config/routes.rb", routes_code, None)
        .expect("routes.rb failed");
    assert_eq!(res2.language, "ruby");

    // Special filename Gemfile
    let gemfile_code = "class GemManager; end";
    let res3 = registry
        .parse_file("Gemfile", gemfile_code, None)
        .expect("Gemfile failed");
    assert_eq!(res3.language, "ruby");
}

#[test]
fn test_registry_skip_generated() {
    let registry = AstRegistry::standard();
    let generated_code =
        "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage pb\ntype Msg struct {}";

    let opts = ParseOptions {
        skip_generated: true,
        ..Default::default()
    };

    let res = registry
        .parse_file("api.pb.go", generated_code, Some(opts))
        .expect("Skip generated failed");

    assert!(res.is_generated);
    assert_eq!(res.nodes.len(), 0);
}
